import { NextResponse } from "next/server";
import { serverProjects } from "@/lib/serverStore";

export const dynamic = "force-dynamic";

export async function GET(
  req: Request,
  { params }: { params: { id: string } }
) {
  const projectId = parseInt(params.id, 10);
  const project = serverProjects.find((p) => p.id === projectId) || serverProjects[0];

  const issues = project?.issues || [];
  const openCount = issues.filter((i: any) => i.status === "open").length;
  const resolvedCount = issues.filter((i: any) => i.status === "resolved").length;

  const content = `# Citation Audit Report: ${project?.title || "Academic Manuscript"}
Date: ${new Date().toLocaleDateString()}
Document: ${project?.doc_filename || "Manuscript.docx"}
Target Journal: ${project?.target_journal || "Journal of Informetrics"}
Total Detected Issues: ${issues.length} (Open: ${openCount}, Resolved: ${resolvedCount})

================================================================================
EXECUTIVE SUMMARY
================================================================================
This audit report summarizes reference integrity verification, bibliographic 
matching, and digital object identifier validation performed by ResearchMate AI.

--------------------------------------------------------------------------------
DETAILED CITATION DEFECTS & CORRECTIONS
--------------------------------------------------------------------------------
${issues.map((issue: any, idx: number) => `
[${idx + 1}] Category: ${issue.category.replace(/_/g, " ").toUpperCase()}
Severity: ${issue.severity.toUpperCase()} | Status: ${issue.status.toUpperCase()}
Location: Page ${issue.page || 1}, Paragraph ${issue.paragraph || 1}
Cited Text: "${issue.cited_text}"
Explanation: ${issue.explanation}
Suggested Correction: ${issue.suggested_correction || "Verify against peer-reviewed venue."}
--------------------------------------------------------------------------------
`).join("")}

================================================================================
Generated by ResearchMate AI - Academic Verification Suite
`;

  return new Response(content, {
    status: 200,
    headers: {
      "Content-Type": "text/markdown; charset=utf-8",
      "Content-Disposition": `attachment; filename="Citation_Audit_Report_${projectId}.md"`,
    },
  });
}
